//! Built-in translations of every [`Text`], chosen by `general.language`
//! (`de`, `es`, `fr`; other languages use English). `[strings]` overrides apply on
//! top. Each pack translates every text and keeps the English `{placeholders}`.

use crate::strings::Text;

/// One language's texts.
pub type Pack = &'static [(Text, &'static str)];

/// The pack for a language tag (by primary subtag: `de-AT` uses `de`).
pub fn pack(language: &str) -> Option<Pack> {
    let primary = language.split(['-', '_']).next().unwrap_or_default();
    PACKS
        .iter()
        .find(|(code, _)| code.eq_ignore_ascii_case(primary))
        .map(|(_, pack)| *pack)
}

