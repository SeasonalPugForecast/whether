#[cfg(test)]
mod tests {
    use super::*;
    use alloc::vec::Vec;

    /// `{name}` placeholders in a text, sorted.
    fn placeholders(text: &str) -> Vec<&str> {
        let mut out: Vec<&str> = text
            .split('{')
            .skip(1)
            .filter_map(|s| s.split_once('}').map(|(name, _)| name))
            .collect();
        out.sort_unstable();
        out
    }

    #[test]
    fn every_pack_translates_every_text_once_with_its_placeholders() {
        let english: Vec<(&str, &str)> = crate::strings::Strings::keys().collect();
        for (code, pack) in PACKS {
            assert_eq!(pack.len(), english.len(), "{code}: every text, once");
            for (i, (text, translated)) in pack.iter().enumerate() {
                assert!(
                    pack[..i].iter().all(|(t, _)| t != text),
                    "{code}: {text:?} twice"
                );
                assert!(!translated.trim().is_empty(), "{code}: {text:?} is empty");
                assert_eq!(
                    placeholders(translated),
                    placeholders(text.default_text()),
                    "{code}: {text:?} keeps the placeholders"
                );
            }
        }
        assert_eq!(LANGUAGES, PACKS.map(|(code, _)| code));
    }

    #[test]
    fn packs_are_found_by_primary_subtag() {
        assert!(pack("de").is_some() && pack("de-AT").is_some() && pack("FR_ca").is_some());
        assert!(pack("en").is_none() && pack("").is_none() && pack("xx").is_none());
    }
}
